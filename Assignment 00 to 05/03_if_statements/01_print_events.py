# even numbers print

def main():
    # This for-loop start at 0 and counts up to 19 (for a total of 20 numbers)
    for i in range(10):
        print(i * 2)  # Use the 'i' value inside the for-loop
   
# Call the main function when "run".
if __name__ == "__main__":
    main()


