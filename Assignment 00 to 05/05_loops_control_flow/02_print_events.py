# print even numbers.
def main():
    for i in range (20):
        print(i * 2)

if __name__ == "__main__":
    main()


# print odd numbers.
def main():
    for i in range(1, 20, 2):   
        print(i)

if __name__ == "__main__":
    main()


# print complete number 1 to 19.
def main():
    for i in range(1, 20, 1):   
        print(i)

if __name__ == "__main__":
    main()
